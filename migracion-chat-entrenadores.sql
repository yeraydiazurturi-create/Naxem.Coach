create table if not exists public.chat_cdm (
  id         bigint generated by default as identity primary key,
  a          uuid not null,                       -- el uuid menor de la pareja
  b          uuid not null,                       -- el uuid mayor de la pareja
  author_id  uuid not null,
  author     text not null default '',
  body       text not null default '',
  kind       text not null default 'text',
  url        text not null default '',
  created_at timestamptz not null default now(),
  constraint chat_cdm_order  check (a < b),
  constraint chat_cdm_author check (author_id = a or author_id = b),
  constraint chat_cdm_len    check (length(body) <= 1000)
);
create index if not exists chat_cdm_ab     on public.chat_cdm (a, b, id desc);
create index if not exists chat_cdm_author on public.chat_cdm (author_id, id desc);
alter table public.chat_cdm enable row level security;

-- ¿Este uuid es personal de Nexum (entrenador activo, nutricionista o administrador)?
create or replace function public.is_staff_id(p uuid) returns boolean
language sql stable security definer set search_path to 'public' as $$
  select exists (select 1 from coaches where id = p and not coalesce(suspendido,false))
      or exists (select 1 from nutricionistas where user_id = p)
      or exists (select 1 from admins where user_id = p)
$$;

-- Directorio del equipo (nombre, foto y rol) para la lista de chats. Solo lo puede leer el personal.
create or replace function public.staff_directory()
returns table(id uuid, nombre text, foto text, rol text)
language plpgsql stable security definer set search_path to 'public' as $$
begin
  if not (is_staff() or is_nutri()) then return; end if;
  return query
  select c.id,
         coalesce(nullif(trim(coalesce(c.nombre,'') || ' ' || coalesce(c.apellidos,'')), ''), nullif(c.empresa_nombre,''), c.email, 'Entrenador'),
         case when length(coalesce(c.foto,'')) <= 250000 and c.foto like 'data:image/%' then c.foto else null end,
         case when exists (select 1 from admins x where x.user_id = c.id) then 'admin' else 'coach' end
    from coaches c
   where c.id <> auth.uid() and not coalesce(c.suspendido,false)
  union all
  select n.user_id, coalesce(nullif(n.nombre,''), 'Nutricionista'),
         case when length(coalesce(n.foto,'')) <= 250000 and n.foto like 'data:image/%' then n.foto else null end,
         'nutri'
    from nutricionistas n where n.user_id <> auth.uid()
  union all
  select a.user_id, coalesce(nullif(a.nombre,''), 'Administrador'), null::text, 'admin'
    from admins a
   where a.user_id <> auth.uid() and not exists (select 1 from coaches c2 where c2.id = a.user_id);
end $$;

revoke all on function public.is_staff_id(uuid), public.staff_directory() from public, anon;
grant execute on function public.is_staff_id(uuid), public.staff_directory() to authenticated;

-- Seguridad por filas: solo ven la conversación sus dos participantes, y solo si son personal de Nexum.
create policy cdm_select on public.chat_cdm for select to authenticated
  using ( (select auth.uid()) in (a, b) and ((select is_staff()) or (select is_nutri())) );

create policy cdm_insert on public.chat_cdm for insert to authenticated
  with check ( author_id = (select auth.uid())
           and ((select is_staff()) or (select is_nutri()))
           and kind in ('text','audio','video','image')
           and is_staff_id(case when author_id = a then b else a end) );

create policy cdm_delete on public.chat_cdm for delete to authenticated
  using ( author_id = (select auth.uid()) );
